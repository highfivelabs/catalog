// BlockedKindsPath is the ranked list of the Config Connector kinds the
// blocked Google Cloud modules lack, for config-connector-extensions.
const BlockedKindsPath = Dir + "/blocked-kinds.md"

// missingKind is one Config Connector kind (or, where there is none, the
// kind a resource type would need) that at least one blocked module lacks.
type missingKind struct {
	Name     string
	Proposed bool            // no kind exists: the name is derived from the resource type
	Classes  map[string]bool // alpha, extensions, none
	Types    map[string]bool // the Terraform resource types it stands for
	Modules  map[string]bool // the blocked modules that lack it
	Alone    int             // modules it is the only missing kind of
	Unblocks []string        // modules the greedy order unblocks when it is added
}

// kindKey names the kind a missing resource type needs: the inventory's
// kind up to its first qualifier ("BigQueryDatasetAccess/BigQueryDataset.spec.access"
// is BigQueryDatasetAccess), or, for a type with no kind, one derived
// from the type (google_compute_router_route_policy: ComputeRouterRoutePolicy).
func kindKey(t TypeRow) (string, bool) {
	k := strings.Trim(t.Kind, `" `)
	if i := strings.IndexAny(k, " /("); i >= 0 {
		k = k[:i]
	}
	if k != "" {
		return k, false
	}
	var b strings.Builder
	for _, part := range strings.Split(strings.TrimPrefix(t.Type, "google_"), "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String(), true
}

// blockedKinds ranks the kinds the blocked Google Cloud modules lack by
// how many modules each unblocks, greedily: at each step the kind that
// completes the most modules (whose every other missing kind is already
// chosen), ties broken by how many blocked modules lack it, then by name.
func blockedKinds(res *Result) ([]*missingKind, int) {
	blocked := map[string]bool{}
	for _, r := range res.Rows {
		if r.Cloud == "gcp" && r.Status == Blocked {
			blocked[r.Module] = true
		}
	}
	kinds := map[string]*missingKind{}
	needs := map[string]map[string]bool{} // module -> kinds it lacks
	for _, t := range res.Types {
		if t.Cloud != "gcp" || !blocked[t.Module] || t.Class == "stable" {
			continue
		}
		name, proposed := kindKey(t)
		k := kinds[name]
		if k == nil {
			k = &missingKind{Name: name, Proposed: proposed, Classes: map[string]bool{}, Types: map[string]bool{}, Modules: map[string]bool{}}
			kinds[name] = k
		}
		k.Classes[t.Class] = true
		k.Types[t.Type] = true
		k.Modules[t.Module] = true
		if needs[t.Module] == nil {
			needs[t.Module] = map[string]bool{}
		}
		needs[t.Module][name] = true
	}
	for _, ks := range needs {
		if len(ks) == 1 {
			for n := range ks {
				kinds[n].Alone++
			}
		}
	}
	left := map[string]map[string]bool{}
	for m, ks := range needs {
		left[m] = map[string]bool{}
		for k := range ks {
			left[m][k] = true
		}
	}
	var order []*missingKind
	chosen := map[string]bool{}
	for len(order) < len(kinds) {
		var best *missingKind
		var bestUnblocks []string
		for _, k := range kinds {
			if chosen[k.Name] {
				continue
			}
			var u []string
			for m := range k.Modules {
				if len(left[m]) == 1 && left[m][k.Name] {
					u = append(u, m)
				}
			}
			if best == nil || len(u) > len(bestUnblocks) ||
				(len(u) == len(bestUnblocks) && (len(k.Modules) > len(best.Modules) ||
					(len(k.Modules) == len(best.Modules) && k.Name < best.Name))) {
				best, bestUnblocks = k, u
			}
		}
		sort.Strings(bestUnblocks)
		best.Unblocks = bestUnblocks
		chosen[best.Name] = true
		for m := range best.Modules {
			delete(left[m], best.Name)
		}
		order = append(order, best)
	}
	return order, len(blocked)
}

func keys(m map[string]bool) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func codeList(xs []string) string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = "`" + x + "`"
	}
	return strings.Join(out, ", ")
}

// blockedKindsPage renders docs/coverage/blocked-kinds.md.
func blockedKindsPage(res *Result) []byte {
	order, nBlocked := blockedKinds(res)
	var b bytes.Buffer
	b.WriteString("# Kinds the blocked Google Cloud modules lack\n\n")
	b.WriteString("Generated by `task coverage` from `modules.csv` and `resource-types.csv`; do not edit. ")
	b.WriteString("A tracked Google Cloud module is `blocked` when one of its resource types has no stable (`v1beta1`) Config Connector kind ([`README.md`](README.md), \"Status\"). ")
	b.WriteString("This page lists every such kind, ranked by how many blocked modules adding it would unblock, for config-connector-extensions to work from.\n\n")
	b.WriteString("**How it ranks.** Greedily: each row is the kind that, added to the rows above it, makes the most blocked modules lack nothing; ties go to the kind more blocked modules lack, then by name. ")
	b.WriteString("*Unblocks* lists those modules, *cumulative* counts them with the rows above. *Lacked by* counts the blocked modules that need the kind at all; *alone* the ones it is the only missing kind of. ")
	b.WriteString("A kind is the inventory's (`gcp-resource-kinds.csv`): an `alpha` kind exists only as `v1alpha1` and needs promoting; a `none` type has no kind, and its name here is derived from the Terraform type (*proposed*). ")
	b.WriteString("Several Terraform types can need one kind (a dataset's IAM members, bindings and access entries are all `BigQueryDatasetAccess`). ")
	b.WriteString("A module that is unblocked still needs its chart; a chart can also port a blocked module with the missing kind refused (`docs/design.md`, \"What Config Connector cannot express is refused, by name\").\n\n")

	fmt.Fprintf(&b, "%d blocked modules lack %d kinds between them.\n\n", nBlocked, len(order))
	b.WriteString("| Rank | Kind | Class | Unblocks | Cumulative | Lacked by | Alone | Terraform resource types |\n")
	b.WriteString("| ---: | --- | --- | --- | ---: | ---: | ---: | --- |\n")
	cum := 0
	for i, k := range order {
		cum += len(k.Unblocks)
		name := "`" + k.Name + "`"
		if k.Proposed {
			name += " (proposed)"
		}
		unblocks := "none alone"
		if len(k.Unblocks) > 0 {
			unblocks = fmt.Sprintf("%d: %s", len(k.Unblocks), codeList(k.Unblocks))
		}
		fmt.Fprintf(&b, "| %d | %s | %s | %s | %d | %d | %d | %s |\n",
			i+1, name, strings.Join(keys(k.Classes), ", "), unblocks, cum, len(k.Modules), k.Alone, codeList(keys(k.Types)))
	}
	b.WriteString("\n## Which modules lack which kinds\n\n")
	b.WriteString("| Module | Missing kinds |\n| --- | --- |\n")
	needs := map[string][]string{}
	for _, k := range order {
		for m := range k.Modules {
			needs[m] = append(needs[m], k.Name)
		}
	}
	for _, r := range res.Rows {
		if r.Cloud != "gcp" || r.Status != Blocked {
			continue
		}
		ks := needs[r.Module]
		sort.Strings(ks)
		fmt.Fprintf(&b, "| `%s` | %d: %s |\n", r.Module, len(ks), codeList(ks))
	}
	return b.Bytes()
}
